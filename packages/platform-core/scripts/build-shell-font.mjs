#!/usr/bin/env node
// Regenerates src/shell/fonts.ts — Inter (variable woff2) embedded as base64 so the
// game shell renders identically on every platform with no external asset or network
// fetch. Run from the package root:  node scripts/build-shell-font.mjs
//
// Subsets are deliberately limited to keep the inline payload small:
//   latin    — EN/ES/FR (Latin-1 Supplement covers all those accents; + œ/Œ)
//   cyrillic — RU/UK and core Cyrillic
// Need Polish/Czech/Turkish/Vietnamese? add 'latin-ext'. Extended Cyrillic? add
// 'cyrillic-ext'. unicode-range values mirror fontsource's @fontsource-variable/inter.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const CDN = 'https://cdn.jsdelivr.net/npm/@fontsource-variable/inter';

// subset -> unicode-range (copied verbatim from the fontsource index.css)
const SUBSETS = [
  ['latin', 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'],
  ['cyrillic', 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116'],
];

async function fetchBytes(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

const here = dirname(fileURLToPath(import.meta.url));
const shellDir = resolve(here, '../src/shell');

const faces = [];
let raw = 0;
for (const [sub, range] of SUBSETS) {
  const bytes = await fetchBytes(`${CDN}/files/inter-${sub}-wght-normal.woff2`);
  raw += bytes.length;
  const b64 = bytes.toString('base64');
  faces.push(
    `@font-face{font-family:'Inter';font-style:normal;font-display:swap;` +
      `font-weight:100 900;src:url(data:font/woff2;base64,${b64}) format('woff2');` +
      `unicode-range:${range};}`,
  );
}

const header = `/* eslint-disable */
// Inter (variable, weight 100–900) embedded as base64 woff2 — self-contained so the
// shell renders identically on every platform with no external asset or network fetch.
// Subsets: latin (covers EN/ES/FR incl. all accents + œ/Œ) + cyrillic (covers RU/UK).
// Inter is licensed under the SIL Open Font License 1.1 — see ./INTER-LICENSE.txt
// (https://github.com/rsms/inter).
// GENERATED by scripts/build-shell-font.mjs — regenerate, don't hand-edit.
`;

const body =
  `export const SHELL_FONT_FAMILY = 'Inter';\n\n` +
  `export const SHELL_FONT_CSS =\n` +
  faces.map((f, i) => `  \`${f}\`` + (i < faces.length - 1 ? ' +\n' : ';\n')).join('');

await writeFile(resolve(shellDir, 'fonts.ts'), header + '\n' + body);
const license = await fetchBytes(`${CDN}/LICENSE`);
await writeFile(resolve(shellDir, 'INTER-LICENSE.txt'), license);

console.log(`wrote src/shell/fonts.ts (${faces.length} faces, ${raw} bytes raw woff2)`);
