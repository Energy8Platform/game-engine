#!/usr/bin/env node
// Regenerates src/ui/pixi-hb/fonts.ts — the Hellbuddha display face embedded as base64 woff2 so the
// shell renders identically everywhere with no runtime fetch (same approach as core/fonts.ts).
//   fonts/clash-regular.woff2 — "Clash" (Regular, the brand's own display face: heavy rounded caps,
//   Latin + Cyrillic, digits, € ₽). One static weight; headings AND numerals use it at 400 —
//   never ask the browser for 700, it would fake-bold an already heavy face.
// Run from the package root:  node scripts/build-hb-fonts.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../fonts/clash-regular.woff2');
const clash = await readFile(src);
const face =
  `@font-face{font-family:'ClashHB';font-style:normal;font-display:swap;font-weight:400;` +
  `src:url(data:font/woff2;base64,${clash.toString('base64')}) format('woff2');}`;

const header = `/* eslint-disable */
// Hellbuddha display face embedded as base64 woff2 — self-contained, no runtime fetch.
//   Clash Regular (fonts/clash-regular.woff2, supplied by the brand) — Latin + Cyrillic, one weight.
// GENERATED by scripts/build-hb-fonts.mjs — regenerate, don't hand-edit.
`;
const body =
  `export const HB_HEAD_FONT_FAMILY = 'ClashHB';\n\n` +
  `export const HB_FONT_CSS =\n  \`${face}\`;\n`;
await writeFile(resolve(here, '../src/ui/pixi-hb/fonts.ts'), header + '\n' + body);
console.log(`wrote fonts.ts: clash ${clash.length}B`);
