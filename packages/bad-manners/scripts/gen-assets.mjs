#!/usr/bin/env node
// Regenerates src/generated/*.ts from brand/ — the Bad Manners kit embedded as base64 / inline SVG, so
// the package renders with no runtime fetch (Stake's CSP blocks data: font/image URLs; bytes decoded in
// JS never hit it). Run from the package root:  node scripts/gen-assets.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const brand = (p) => resolve(root, 'brand', p);
const out = (p) => resolve(root, 'src/generated', p);
await mkdir(out(''), { recursive: true });

const HEADER = (what) => `/* eslint-disable */\n// ${what}\n// GENERATED by scripts/gen-assets.mjs from brand/ — regenerate, don't hand-edit.\n\n`;
const b64 = async (p) => (await readFile(brand(p))).toString('base64');

// ── fonts ──────────────────────────────────────────────────────────────────────
const LATIN =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const CYRILLIC = 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116';
const FACES = [
  ['BMDisplay', '400', 'luckiest-guy-latin-400-normal.woff2', LATIN],
  ...['600', '800', '900'].flatMap((w) => [
    ['BMSans', w, `montserrat-latin-${w}-normal.woff2`, LATIN],
    ['BMSans', w, `montserrat-cyrillic-${w}-normal.woff2`, CYRILLIC],
  ]),
];
let fonts = HEADER('Luckiest Guy 400 (Apache 2.0) + Montserrat 600/800/900 latin+cyrillic (SIL OFL 1.1) as base64 woff2.');
fonts += 'export const FONT_FACES: Array<{ family: string; weight: string; range: string; b64: string }> = [\n';
for (const [family, weight, file, range] of FACES) {
  fonts += `  { family: '${family}', weight: '${weight}', range: '${range}', b64: '${await b64(`fonts/${file}`)}' },\n`;
}
fonts += '];\n';
await writeFile(out('fonts.ts'), fonts);

// ── atlas + raster logos ───────────────────────────────────────────────────────
const atlasJson = JSON.parse(await readFile(brand('atlas/bm-ui@2x.json'), 'utf8'));
let atlas = HEADER('The kit atlas (bm-ui@2x: icon/* + ui/*) and the face mark the shell draws.');
atlas += `export const ATLAS_PNG = '${await b64('atlas/bm-ui@2x.png')}';\n\n`;
atlas += `export const ATLAS_FRAMES: Record<string, { x: number; y: number; w: number; h: number }> = ${JSON.stringify(
  Object.fromEntries(Object.entries(atlasJson.frames).map(([k, f]) => [k, f.frame])),
)};\n\n`;
atlas += `/** bm-mark-face, 246×256. */\nexport const FACE_PNG = '${await b64('logo/bm-mark-face.png')}';\n`;
await writeFile(out('atlas.ts'), atlas);

// ── intro SVG layers (inline DOM — the C2PA <metadata> block is dropped) ──────
const svg = async (p) =>
  (await readFile(brand(p), 'utf8'))
    .replace(/<metadata>[\s\S]*?<\/metadata>/g, '')
    .replace(/\s+xmlns:c2pa="[^"]*"/, '')
    .replace(/<title>[^<]*<\/title>/g, '') // no hover tooltips on the loader
    .replace(/\s+id="[^"]*"/g, '') // unreferenced, and generic ids ("face", "bad") would leak into the host page
    .trim();
const LAYERS = {
  manners: 'intro-manners.svg',
  badClosed: 'intro-bad-closed.svg',
  bad: 'intro-bad.svg',
  tongue: 'intro-tongue.svg',
  bubble: 'intro-bubble.svg',
  face: 'bm-mark-face.svg',
};
let intro = HEADER('Intro layers (brand/logo/*.svg) as inline SVG markup.');
intro += 'export const INTRO_SVG: Record<string, string> = {\n';
for (const [id, file] of Object.entries(LAYERS)) intro += `  ${id}: ${JSON.stringify(await svg(`logo/${file}`))},\n`;
intro += '};\n';
await writeFile(out('intro-svg.ts'), intro);

console.log('wrote src/generated/{fonts,atlas,intro-svg}.ts');
