#!/usr/bin/env node
// Regenerates src/generated/assets.ts from brand/: the DOGMATIC outline artwork (collar, D tag,
// wordmark and LOADING lettering in one 1671×941 picture) and Manrope 800 cut to the loader's
// percentage glyphs. Embedded as base64 — nothing is fetched at runtime (Stake's CSP). Run from the
// package root:  node scripts/gen-assets.mjs
//
// The vendor fork itself (src/shell/vendor/) is copied from the provider's preview project; to refresh
// it from a new drop, copy the files reachable from that project's src/shell.ts and rewrite their
// `@/` imports to relative paths (that is all the copy changes).
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const b64 = async (p) => (await readFile(resolve(root, 'brand', p))).toString('base64');
await mkdir(resolve(root, 'src/generated'), { recursive: true });
await writeFile(
  resolve(root, 'src/generated/assets.ts'),
  `/* eslint-disable */
// GENERATED by scripts/gen-assets.mjs from brand/ — regenerate, don't hand-edit.

/** brand/dogmatic-outline.jpg, 1671×941. */
export const ART_JPG = '${await b64('dogmatic-outline.jpg')}';
export const ART_W = 1671;
export const ART_H = 941;

/** Manrope 800 (SIL OFL 1.1 — brand/Manrope-OFL.txt), subset to 0-9 and %. */
export const MANROPE_WOFF2 = '${await b64('manrope-800-digits.woff2')}';
`,
);
console.log('wrote src/generated/assets.ts');
